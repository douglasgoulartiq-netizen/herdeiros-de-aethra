import assert from 'node:assert/strict';
import {readFileSync,readdirSync} from 'node:fs';
import {criarPersonagem} from '../src/systems/CharacterFactory.js';
import {estadoGachaInicial,invocarIniciante,definirTimeAtivo} from '../src/systems/GachaSystem.js';
import {registrarCombateTutorial} from '../src/ui/LiveTutorialUI.js';
const dir = new URL('../src/data/',import.meta.url);
const dados = Object.fromEntries(readdirSync(dir).filter(f=>f.endsWith('.json')).map(f=>[f.slice(0,-5),JSON.parse(readFileSync(new URL(f,dir),'utf8'))]));
const p = criarPersonagem({nome:'Teste',raca:dados.races[0].id,classe:dados.classes[0].id,antecedente:dados.backgrounds[0].id,traco:dados.traits[0].id},dados);
p.gacha = estadoGachaInicial();
p.tutorialMissao = {status:'em_andamento',etapa:'invocar',vitorias:0};
for(let i=0;i<3;i++) assert.equal(invocarIniciante(p,dados.gachaRoster,dados).ok,true);
assert.equal(new Set(p.gacha.personagensObtidos.map(x=>x.rosterId)).size,3,'Three distinct real companions');
assert.equal(p.gacha.timeAtivo.length,0,'Formation requires player action');
assert.equal(p.gacha.beginner.gratisRestantes,7,'Uses real free banner allowance');
definirTimeAtivo(p,p.gacha.personagensObtidos.map(x=>x.uid));
assert.equal(p.gacha.timeAtivo.length,3);
registrarCombateTutorial(p,'vitoria');
assert.equal(p.tutorialMissao.vitorias,0,'No counting before battle step');
p.tutorialMissao.etapa='batalhas';
registrarCombateTutorial(p,'derrota'); registrarCombateTutorial(p,'fuga');
assert.equal(p.tutorialMissao.vitorias,0);
registrarCombateTutorial(p,'vitoria'); registrarCombateTutorial(p,'vitoria'); registrarCombateTutorial(p,'vitoria');
assert.equal(p.tutorialMissao.vitorias,2);
console.log('PASS: real recruits, manual formation, free allowance, victory/defeat/escape and cap.');
